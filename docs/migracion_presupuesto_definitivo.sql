-- Presupuesto definitivo: documento que se emite cuando la reparación finaliza (orden en estado 'listo').
-- Guarda una copia de los conceptos e importes de la reparación para que no cambien aunque
-- después varíen los precios del catálogo o los datos del cliente o del vehículo.
-- Ejecutar una sola vez en cada base de datos ya creada (motorlabdb y motorlab_testdb).
-- Es seguro repetirlo: no hace nada si las tablas ya existen.

BEGIN;

CREATE TABLE IF NOT EXISTS presupuestos_definitivos (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id             INTEGER       NOT NULL,
  presupuesto_id       INTEGER       NOT NULL,
  emitido_en           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cliente_nombre       VARCHAR(100)  NOT NULL,
  cliente_email        VARCHAR(150)  NOT NULL,
  cliente_telefono     VARCHAR(20)   NOT NULL,
  vehiculo_matricula   VARCHAR(10)   NOT NULL,
  vehiculo_marca       VARCHAR(50)   NOT NULL,
  vehiculo_modelo      VARCHAR(80)   NOT NULL,
  vehiculo_version     VARCHAR(80),
  vehiculo_anio        SMALLINT      NOT NULL,
  vehiculo_kilometros  INTEGER       NOT NULL,
  tipo_servicio        VARCHAR(20)   NOT NULL,
  subtotal_mano_obra   NUMERIC(10,2) NOT NULL,
  subtotal_piezas      NUMERIC(10,2) NOT NULL,
  subtotal             NUMERIC(10,2) NOT NULL,
  iva_porcentaje       NUMERIC(4,2)  NOT NULL,
  iva                  NUMERIC(10,2) NOT NULL,
  total                NUMERIC(10,2) NOT NULL,
  CONSTRAINT uq_presupuestos_definitivos_orden UNIQUE (orden_id),   -- uno por orden: evita duplicados
  CONSTRAINT fk_presupuestos_definitivos_orden FOREIGN KEY (orden_id) REFERENCES ordenes_trabajo (id),
  CONSTRAINT fk_presupuestos_definitivos_presupuesto FOREIGN KEY (presupuesto_id) REFERENCES presupuestos (id),
  CONSTRAINT ck_presupuestos_definitivos_total CHECK (total >= 0)
);

CREATE TABLE IF NOT EXISTS lineas_presupuesto_definitivo (
  id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  presupuesto_definitivo_id  INTEGER       NOT NULL,
  posicion                   SMALLINT      NOT NULL,
  tipo                       VARCHAR(10)   NOT NULL,
  referencia                 VARCHAR(30),                -- referencia de la pieza, si es una pieza
  concepto                   VARCHAR(150)  NOT NULL,
  cantidad                   NUMERIC(8,2)  NOT NULL,
  precio_unitario            NUMERIC(10,2) NOT NULL,
  importe                    NUMERIC(10,2) NOT NULL,
  CONSTRAINT fk_lineas_definitivo FOREIGN KEY (presupuesto_definitivo_id)
    REFERENCES presupuestos_definitivos (id) ON DELETE CASCADE,
  CONSTRAINT ck_lineas_definitivo_tipo CHECK (tipo IN ('pieza', 'mano_obra'))
);

CREATE INDEX IF NOT EXISTS idx_lineas_definitivo ON lineas_presupuesto_definitivo (presupuesto_definitivo_id);

COMMIT;
