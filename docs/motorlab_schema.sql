-- 8. REGLAS DE NEGOCIO EN LA BASE DE DATOS (funciones y triggers)
-- ---------------------------------------------------------------------

-- 8.1 Recalcula subtotal, IVA y total de un presupuesto a partir de sus líneas
CREATE FUNCTION recalcular_presupuesto(p_presupuesto_id INTEGER) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE presupuestos
     SET subtotal = (SELECT COALESCE(SUM(importe), 0)
                       FROM lineas_presupuesto
                      WHERE presupuesto_id = p_presupuesto_id)
   WHERE id = p_presupuesto_id;

  UPDATE presupuestos
     SET iva   = ROUND(subtotal * iva_porcentaje / 100, 2),
         total = subtotal + ROUND(subtotal * iva_porcentaje / 100, 2)
   WHERE id = p_presupuesto_id;
END $$;

-- 8.2 Cada vez que cambia una línea, se recalculan los totales automáticamente
CREATE FUNCTION trg_lineas_recalcular() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM recalcular_presupuesto(OLD.presupuesto_id);
  ELSE
    PERFORM recalcular_presupuesto(NEW.presupuesto_id);
  END IF;
  RETURN NULL;
END $$;

CREATE TRIGGER trg_lineas
AFTER INSERT OR UPDATE OR DELETE ON lineas_presupuesto
FOR EACH ROW EXECUTE FUNCTION trg_lineas_recalcular();

-- 8.3 Regla de urgencia: frenos o vehículo no seguro => urgencia ALTA (sin IA)
CREATE FUNCTION trg_ordenes_urgencia() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.conduccion_segura = 'no' OR NEW.tipo_servicio = 'frenos' THEN
    NEW.urgencia := 'alta';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_ordenes_urgencia
BEFORE INSERT ON ordenes_trabajo
FOR EACH ROW EXECUTE FUNCTION trg_ordenes_urgencia();

-- 8.4 Actualiza actualizado_en en cada modificación de una orden (equivale a ON UPDATE de MySQL)
CREATE FUNCTION trg_ordenes_actualizado() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado_en := CURRENT_TIMESTAMP;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_ordenes_actualizado
BEFORE UPDATE ON ordenes_trabajo
FOR EACH ROW EXECUTE FUNCTION trg_ordenes_actualizado();

