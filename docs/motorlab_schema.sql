CREATE INDEX idx_ordenes_estado   ON ordenes_trabajo (estado);
CREATE INDEX idx_ordenes_urgencia ON ordenes_trabajo (urgencia);
CREATE INDEX idx_ordenes_mecanico ON ordenes_trabajo (mecanico_id);
CREATE INDEX idx_ordenes_vehiculo ON ordenes_trabajo (vehiculo_id);

-- ---------------------------------------------------------------------
-- 5. PRESUPUESTOS (uno por orden) y sus LINEAS
-- ---------------------------------------------------------------------
CREATE TABLE presupuestos (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id               INTEGER       NOT NULL,
  estado                 VARCHAR(10)   NOT NULL DEFAULT 'borrador',
  iva_porcentaje         NUMERIC(4,2)  NOT NULL DEFAULT 21.00,
  subtotal               NUMERIC(10,2) NOT NULL DEFAULT 0.00,   -- los calcula la BD (ver triggers)
  iva                    NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  total                  NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  tiempo_estimado_horas  NUMERIC(4,1),
  garantia_meses         SMALLINT      NOT NULL DEFAULT 24,
  motivo_rechazo         VARCHAR(255),
  enviado_en             TIMESTAMP,
  respondido_en          TIMESTAMP,
  creado_en              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_presupuestos_orden UNIQUE (orden_id),
  CONSTRAINT fk_presupuestos_orden FOREIGN KEY (orden_id) REFERENCES ordenes_trabajo (id),
  CONSTRAINT ck_presupuestos_estado   CHECK (estado IN ('borrador', 'enviado', 'autorizado', 'rechazado')),
  CONSTRAINT ck_presupuestos_garantia CHECK (garantia_meses >= 0)
);

CREATE TABLE lineas_presupuesto (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  presupuesto_id   INTEGER       NOT NULL,
  tipo             VARCHAR(10)   NOT NULL,
  pieza_id         INTEGER,                                  -- solo si tipo = 'pieza'
  concepto         VARCHAR(150)  NOT NULL,
  cantidad         NUMERIC(8,2)  NOT NULL,                   -- unidades, o horas si es mano de obra
  precio_unitario  NUMERIC(10,2) NOT NULL,                   -- precio por unidad, o tarifa/hora
  importe          NUMERIC(10,2) GENERATED ALWAYS AS (ROUND(cantidad * precio_unitario, 2)) STORED,
  CONSTRAINT fk_lineas_presupuesto FOREIGN KEY (presupuesto_id) REFERENCES presupuestos (id) ON DELETE CASCADE,
  CONSTRAINT fk_lineas_pieza       FOREIGN KEY (pieza_id)       REFERENCES piezas (id),
  CONSTRAINT ck_lineas_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_lineas_precio   CHECK (precio_unitario >= 0),
  CONSTRAINT ck_lineas_tipo CHECK (
       (tipo = 'pieza'     AND pieza_id IS NOT NULL)
    OR (tipo = 'mano_obra' AND pieza_id IS NULL)
  )
);
CREATE INDEX idx_lineas_presupuesto ON lineas_presupuesto (presupuesto_id);

-- ---------------------------------------------------------------------
-- 6. EVENTOS_SEGUIMIENTO (línea de tiempo que ve el cliente)
