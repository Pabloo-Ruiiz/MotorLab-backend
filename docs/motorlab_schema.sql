-- ---------------------------------------------------------------------
-- 1. USUARIOS (clientes, mecánicos y administradores)
--    Los "ENUM" se modelan con VARCHAR + CHECK (así JPA los lee como texto).
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(100) NOT NULL,
  email              VARCHAR(150) NOT NULL,
  telefono           VARCHAR(20)  NOT NULL,
  password_hash      VARCHAR(255) NOT NULL,                 -- hash bcrypt, nunca la contraseña
  rol                VARCHAR(10)  NOT NULL DEFAULT 'cliente',
  activo             BOOLEAN      NOT NULL DEFAULT TRUE,    -- baja lógica
  consentimiento_en  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- RGPD
  creado_en          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_usuarios_email UNIQUE (email),
  CONSTRAINT ck_usuarios_rol   CHECK (rol IN ('cliente', 'mecanico', 'admin'))
);

-- ---------------------------------------------------------------------
-- 2. VEHICULOS
-- ---------------------------------------------------------------------
CREATE TABLE vehiculos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER      NOT NULL,
  matricula   VARCHAR(10)  NOT NULL,            -- en mayúsculas y sin espacios: 4821KLB
  marca       VARCHAR(50)  NOT NULL,
  modelo      VARCHAR(80)  NOT NULL,
  version     VARCHAR(80),                      -- p. ej. 1.5 TSI
  anio        SMALLINT     NOT NULL,
  kilometros  INTEGER      NOT NULL,
  activo      BOOLEAN      NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_vehiculos_matricula UNIQUE (matricula),
  CONSTRAINT fk_vehiculos_usuario   FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
  CONSTRAINT ck_vehiculos_anio      CHECK (anio BETWEEN 1980 AND 2100),
  CONSTRAINT ck_vehiculos_km        CHECK (kilometros >= 0)
);
CREATE INDEX idx_vehiculos_usuario ON vehiculos (usuario_id);

-- ---------------------------------------------------------------------
-- 3. PIEZAS (catálogo y stock)
-- ---------------------------------------------------------------------
CREATE TABLE piezas (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia  VARCHAR(30)   NOT NULL,
  nombre      VARCHAR(120)  NOT NULL,
  precio      NUMERIC(10,2) NOT NULL,
  stock       INTEGER       NOT NULL DEFAULT 0,
  activa      BOOLEAN       NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_piezas_referencia UNIQUE (referencia),
  CONSTRAINT ck_piezas_precio     CHECK (precio >= 0),
  CONSTRAINT ck_piezas_stock      CHECK (stock >= 0)       -- el stock nunca puede quedar negativo
);

-- ---------------------------------------------------------------------
-- 4. ORDENES_TRABAJO (la solicitud del cliente ES la orden en su primer estado)
--    El número de orden empieza en 2481 para parecerse al caso de demostración.
-- ---------------------------------------------------------------------
CREATE TABLE ordenes_trabajo (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2481) PRIMARY KEY,
  vehiculo_id         INTEGER      NOT NULL,
  mecanico_id         INTEGER,
  -- Datos que introduce el cliente (formulario de solicitud)
  tipo_servicio       VARCHAR(20)  NOT NULL,
  sintoma             TEXT         NOT NULL,
  cuando_ocurre       VARCHAR(15),
  conduccion_segura   VARCHAR(5)   NOT NULL,
  urgencia            VARCHAR(5)   NOT NULL DEFAULT 'media',
  fecha_preferida     DATE         NOT NULL,
  franja_preferida    VARCHAR(6)   NOT NULL,
  contacto_preferido  VARCHAR(8)   NOT NULL DEFAULT 'telefono',
  -- Gestión interna del taller
  estado              VARCHAR(30)  NOT NULL DEFAULT 'solicitud_recibida',
  elevador            VARCHAR(20),
  fecha_entrada       TIMESTAMP,
  fecha_estimada      TIMESTAMP,
  creado_en           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ordenes_vehiculo FOREIGN KEY (vehiculo_id) REFERENCES vehiculos (id),
  CONSTRAINT fk_ordenes_mecanico FOREIGN KEY (mecanico_id) REFERENCES usuarios (id),
  CONSTRAINT ck_ordenes_sintoma  CHECK (char_length(sintoma) >= 20),
  CONSTRAINT ck_ordenes_tipo     CHECK (tipo_servicio IN ('frenos', 'motor', 'aceite_filtros', 'neumaticos', 'electricidad', 'itv', 'otro')),
  CONSTRAINT ck_ordenes_cuando   CHECK (cuando_ocurre IS NULL OR cuando_ocurre IN ('al_frenar', 'al_arrancar', 'en_marcha', 'siempre', 'otro')),
  CONSTRAINT ck_ordenes_segura   CHECK (conduccion_segura IN ('si', 'no', 'no_se')),
  CONSTRAINT ck_ordenes_urgencia CHECK (urgencia IN ('baja', 'media', 'alta')),
  CONSTRAINT ck_ordenes_franja   CHECK (franja_preferida IN ('manana', 'tarde')),
  CONSTRAINT ck_ordenes_contacto CHECK (contacto_preferido IN ('telefono', 'email')),
  CONSTRAINT ck_ordenes_estado   CHECK (estado IN ('solicitud_recibida', 'pendiente_presupuesto', 'presupuesto_enviado',
                                                   'presupuesto_autorizado', 'recibido', 'en_preparacion', 'esperando_pieza',
                                                   'arreglando', 'listo', 'entregado', 'rechazada', 'cancelada'))
