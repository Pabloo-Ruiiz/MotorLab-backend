  usuario_id   INTEGER,                                      -- quién hizo el cambio
  CONSTRAINT fk_eventos_orden   FOREIGN KEY (orden_id)   REFERENCES ordenes_trabajo (id) ON DELETE CASCADE,
  CONSTRAINT fk_eventos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_eventos_orden ON eventos_seguimiento (orden_id, fecha_hora);

