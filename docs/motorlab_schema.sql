-- 9. VISTA: resumen de órdenes con porcentaje de progreso
-- ---------------------------------------------------------------------
CREATE VIEW v_ordenes_resumen AS
SELECT
  o.id                AS orden_id,
  o.estado,
  CASE o.estado
    WHEN 'recibido'        THEN 20
    WHEN 'en_preparacion'  THEN 40
    WHEN 'esperando_pieza' THEN 60
    WHEN 'arreglando'      THEN 80
    WHEN 'listo'           THEN 100
    WHEN 'entregado'       THEN 100
    ELSE 0
  END                 AS progreso,
  o.urgencia,
  o.tipo_servicio,
  o.sintoma,
  o.elevador,
  o.fecha_entrada,
  o.fecha_estimada,
  v.id                AS vehiculo_id,
  v.matricula,
  v.marca,
  v.modelo,
  u.id                AS cliente_id,
  u.nombre            AS cliente_nombre,
  m.id                AS mecanico_id,
  m.nombre            AS mecanico_nombre,
  p.estado            AS presupuesto_estado,
  p.total             AS presupuesto_total
FROM ordenes_trabajo o
JOIN vehiculos v         ON v.id = o.vehiculo_id
JOIN usuarios  u         ON u.id = v.usuario_id
LEFT JOIN usuarios m     ON m.id = o.mecanico_id
LEFT JOIN presupuestos p ON p.orden_id = o.id;

